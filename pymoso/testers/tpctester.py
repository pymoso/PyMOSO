from ..problems import probtpc
from math import sin, exp, sqrt
from ..moso import dh, sum_left_to_right


df = 2

def true_g(x):
    """
    Compute the expected values of a point.

    Parameters
    ----------
    x : tuple of int
        A feasible point

    Returns
    -------
    tuple of float
        The objective values
    """
    x = tuple(i/df for i in x)
    s = [sin(i) for i in x]
    chisquare = 1.0
    sum1 = [-10*chisquare*exp(-0.2*sqrt(x[i]**2 + x[i+1]**2)) for i in [0, 1]]
    sum2 = [chisquare*(pow(abs(x[i]), 0.8) + 5*pow(s[i], 3)) for i in [0, 1, 2]]
    obj1 = sum_left_to_right(sum1)
    obj2 = sum_left_to_right(sum2)
    return obj1, obj2


def get_ranx0(rng):
    """
    Uniformly sample from the feasible space.

    Parameters
    ----------
    rng : prng.MRG32k3a object

    Returns
    -------
    x0 : tuple of int
        The randomly chosen point
    """
    xr = range(-5*df, 5*df + 1)
    x1 = rng.choice(xr)
    x2 = rng.choice(xr)
    x3 = rng.choice(xr)
    x0 = (x1, x2, x3)
    return x0


class TPCTester(object):
    """
    Store useful data for working with Test Problem C.

    Attributes
    ----------
    ranorc : chnbase.Oracle class
    true_g : function
    soln : list of set of tuple of int
        The dissertation's 516 N_1-local weakly efficient sets, as
        decision points (see soln)
    soln_images : list of list of tuple of float
        true_g of each point of each set in soln, computed when the
        tester is made
    get_ranx0 : function
    """
    def __init__(self):
        self.ranorc = probtpc.ProbTPC
        self.true_g = true_g
        self.soln = soln
        # 4,273 point instances over 73 distinct points: image each once
        images = {x: self.true_g(x) for x in set().union(*soln)}
        self.soln_images = [[images[x] for x in lwes] for lwes in soln]
        self.get_ranx0 = get_ranx0

    def metric(self, eles):
        """
        Compute a metric from a simulated solution to the true solution.

        Parameters
        ----------
        eles : set of tuple of numbers
            Simulated solution

        Returns
        -------
        float
            The performance metric
        """
        efrontier = []
        for point in eles:
            objs = self.true_g(point)
            efrontier.append(objs)
        distlist = []
        for lwes in self.soln_images:
            dist = dh(efrontier, lwes)
            distlist.append(dist)
        return min(distlist)


